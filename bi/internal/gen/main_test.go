const testBanner = "/*!\n * Bootstrap Icons v9.8.7 (https://example.com/)\n */"

func TestParse(gt *testing.T) {
	t := devtest.ParallelT(gt)
	css := testBanner + `.bi::before,[class^=bi-]::before{display:inline-block}` +
		`.bi-b::before{content:"\f101"}.bi-a-1::before { content: "\f102"; }.bi-9::before{content:"\f103"}`
	version, icons, err := parse([]byte(css))
	t.Must(be.NoError(err))
	t.Must(be.Equal("9.8.7", version))
	t.Must(be.DeepEqual([]icon{{"B", "b"}, {"A1", "a-1"}, {"Num9", "9"}}, icons))

	src, err := generate([]byte(css))
	t.Must(be.NoError(err))
	s := string(src)
	t.Must(be.Substring(s, `const Version = "9.8.7"`))
	t.Must(be.Substring(s, `A1   Icon = "a-1"`))
	// byName sorts "9" < "a-1" < "b": indexes 2, 1, 0.
	t.Must(be.Substring(s, "var byName = [...]uint16{\n\t2, 1, 0,\n}"))
}

func TestParseRejects(gt *testing.T) {
	t := devtest.ParallelT(gt)
	for _, c := range []struct {
		name string
		css  string
		msg  string
	}{
		{"no banner", `.bi-a::before{content:"\f101"}`, "banner"},
		{"banner not first", `x` + testBanner + `.bi-a::before{content:"\f101"}`, "banner"},
		{"no icons", testBanner + `.bi::before{display:inline-block}`, "no icon rules"},
		{"upper case", testBanner + `.bi-Alarm::before{content:"\f101"}`, "invalid icon name"},
		{"double hyphen", testBanner + `.bi-a--b::before{content:"\f101"}`, "invalid icon name"},
		{"trailing hyphen", testBanner + `.bi-a-::before{content:"\f101"}`, "invalid icon name"},
		{"empty name", testBanner + `.bi-::before{content:"\f101"}`, "invalid icon name"},
		{"duplicate", testBanner + `.bi-a::before{content:"\f101"}.bi-a::before{content:"\f102"}`, "duplicate"},
		{"collision", testBanner + `.bi-a1::before{content:"\f101"}.bi-a-1::before{content:"\f102"}`, "both map to"},
		{"reserved", testBanner + `.bi-version::before{content:"\f101"}`, "reserved"},
		{"grouped selectors", testBanner + `.bi-a::before,.bi-b::before{content:"\f101"}`, "expected shape"},
		{"other shape", testBanner + `.bi-a::after{content:"\f101"}`, "expected shape"},
		{"no content", testBanner + `.bi-a::before{color:red}`, "expected shape"},
	} {
		_, _, err := parse([]byte(c.css))
		t.Mustf(be.ErrorContains(err, c.msg), "case %s", c.name)
		_, err = generate([]byte(c.css))
		t.Mustf(be.Error(err), "case %s: generate", c.name)
	}
}

func TestRun(gt *testing.T) {
	t := devtest.ParallelT(gt)
	dir := t.TempDir()
	cssPath := filepath.Join(dir, "icons.css")
	outPath := filepath.Join(dir, "list.go")
	t.Must(be.NoError(os.WriteFile(cssPath, []byte(testBanner+`.bi-a::before{content:"\f101"}`), 0o600)))
	t.Must(be.NoError(run(cssPath, outPath)))
	out, err := os.ReadFile(outPath)
	t.Must(be.NoError(err))
	t.Must(be.Substring(string(out), `A Icon = "a"`))

	t.Must(be.ErrorContains(run(filepath.Join(dir, "missing.css"), outPath), "open stylesheet"))

	bad := filepath.Join(dir, "bad.css")
	t.Must(be.NoError(os.WriteFile(bad, []byte(`.bi-a::before{content:"\f101"}`), 0o600)))
	t.Must(be.ErrorContains(run(bad, outPath), "banner"))

	big := filepath.Join(dir, "big.css")
	t.Must(be.NoError(os.WriteFile(big, []byte(strings.Repeat(" ", maxCSSSize+1)), 0o600)))
	t.Must(be.ErrorContains(run(big, outPath), "larger than"))
}
